# بخش 11 : دستور Break
# ===============================================================

print("\n==============================")
print("Break Statement")
print("==============================\n")

# دستور break باعث می‌شود حلقه بلافاصله متوقف شود.
# حتی اگر اعضای دیگری باقی مانده باشند،
# دیگر حلقه ادامه پیدا نمی‌کند.
#
# اجرای برنامه از اولین دستور بعد از حلقه ادامه خواهد یافت.

fruits = ["Apple", "Banana", "Orange", "Mango", "Kiwi"]

for fruit in fruits:

    print("Current Fruit :", fruit)

    # اگر مقدار فعلی Orange باشد
    # حلقه متوقف خواهد شد.
    if fruit == "Orange":
        print("Orange Found -> Stop Loop")
        break

print("\nLoop Finished\n")


