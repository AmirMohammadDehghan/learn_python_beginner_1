# 27. Union
# -----------------------------------------------------------------------------

print("\n--- 27) Union ---")

python_students = {"Ali", "Sara", "Mina"}
java_students = {"Mina", "Reza", "Nima"}

# Union یعنی تمام اعضای هر دو Set، بدون تکرار.
