# Tuple:
# Ordered + Indexed + Duplicate Allowed + Immutable
#
# Set:
# Unordered + No Index + Unique + Mutable


# =============================================================================
# نکات مهم مدرس
# =============================================================================

# 1) Tuple:
#    - با () معمولاً نوشته می‌شود.
#    - Index دارد.
#    - Slicing دارد.
#    - Duplicate مجاز است.
#    - Immutable است.
#    - count() و index() را دارد.
#
# 2) Tuple تک‌عضوی:
#    - ("Python",)  --> Tuple
#    - ("Python")   --> str
#
# 3) Set:
#    - Duplicate را حذف می‌کند.
#    - Index ندارد.
#    - add() برای یک آیتم
#    - update() برای چند آیتم/iterable
#    - remove() اگر آیتم نباشد خطا می‌دهد.
#    - discard() اگر آیتم نباشد خطا نمی‌دهد.
#    - pop() یک عنصر را حذف و برمی‌گرداند؛ روی "آخرین عنصر" حساب نکنید.
#    - union() و | برای اجتماع
#    - intersection() و & برای اشتراک
#
# 4) Set خالی:
#    - {}      --> dict
#    - set()   --> set
#
# 5) در مثال‌های آموزشی، برای نمایش مرتب و قابل پیش‌بینی Set:
#       sorted(my_set)
#    استفاده شده است.
#
# 6) Set ترتیب مشخصی ندارد؛ بنابراین نباید ترتیب خروجی آن را بخشی از منطق
