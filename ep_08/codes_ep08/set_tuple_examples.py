print("After discard:", fruits)

# تفاوت مهم:
# اگر آیتم وجود نداشته باشد، discard() خطا ایجاد نمی‌کند.
fruits.discard("orange")

print("Discard non-existing item: no error")


# -----------------------------------------------------------------------------
# 26. pop() در Set
# -----------------------------------------------------------------------------

print("\n--- 26) pop() ---")

fruits = {"apple", "banana", "cherry"}

# pop() یک عنصر را حذف می‌کند و همان عنصر را برمی‌گرداند.
