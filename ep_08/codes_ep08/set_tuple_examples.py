# -----------------------------------------------------------------------------
# 25. Remove Items با discard()
# -----------------------------------------------------------------------------

print("\n--- 25) discard() ---")

fruits = {"apple", "banana", "cherry"}

# discard(value) هم آیتم را حذف می‌کند.
