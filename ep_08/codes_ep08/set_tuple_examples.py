print("Python students:", python_students)
print("Java students:", java_students)
print("Union:", sorted(all_students))


# -----------------------------------------------------------------------------
# 28. Union با عملگر |
# -----------------------------------------------------------------------------

print("\n--- 28) Union با | ---")

python_students = {"Ali", "Sara", "Mina"}
