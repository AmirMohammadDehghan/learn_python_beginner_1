# بخش ۱) TUPLE
# =============================================================================

print("\n" + "=" * 70)
print("بخش ۱: TUPLE")
print("=" * 70)


# -----------------------------------------------------------------------------
# 1. معرفی Tuple
# -----------------------------------------------------------------------------

print("\n--- 1) معرفی Tuple ---")

# Tuple برای نگهداری چند مقدار در یک متغیر استفاده می‌شود.
# Tuple معمولاً با پرانتز () نوشته می‌شود.
fruits = ("apple", "banana", "cherry")

print("Tuple:", fruits)

# type() نوع داده را به ما نشان می‌دهد.
print("Type:", type(fruits))


# -----------------------------------------------------------------------------
# 2. ویژگی‌های مهم Tuple
# -----------------------------------------------------------------------------

print("\n--- 2) ویژگی‌های مهم Tuple ---")

# Tuple دارای ترتیب است (Ordered).
# بنابراین ترتیب قرار گرفتن مقادیر حفظ می‌شود.
ordered_items = ("first", "second", "third")
print("Ordered:", ordered_items)

# Tuple می‌تواند مقدار تکراری داشته باشد (Duplicate).
duplicate_items = ("apple", "banana", "apple", "cherry", "banana")
print("Duplicates are allowed:", duplicate_items)

# Tuple دارای Index است.
# اولین آیتم Index برابر 0 دارد.
print("First item:", ordered_items[0])


# -----------------------------------------------------------------------------
# 3. ساخت Tuple یک‌عضوی
# -----------------------------------------------------------------------------

print("\n--- 3) Tuple یک‌عضوی ---")

# نکته بسیار مهم:
# برای ساخت Tuple تک‌عضوی، وجود ویرگول ضروری است.
one_item_tuple = ("Python",)

print("One-item tuple:", one_item_tuple)
print("Type:", type(one_item_tuple))

# این فقط یک رشته است، نه Tuple.
not_a_tuple = ("Python")
print("Without comma:", not_a_tuple)
print("Type:", type(not_a_tuple))


# -----------------------------------------------------------------------------
# 4. Access Items
# -----------------------------------------------------------------------------

print("\n--- 4) Access Items ---")

fruits = ("apple", "banana", "cherry", "orange")

# دسترسی به آیتم با Index
print("Index 0:", fruits[0])
print("Index 2:", fruits[2])


# -----------------------------------------------------------------------------
# 5. Negative Indexing
# -----------------------------------------------------------------------------

print("\n--- 5) Negative Indexing ---")

# -1 یعنی آخرین آیتم
# -2 یعنی یکی مانده به آخر
# -3 یعنی سه‌مین آیتم از انتها
print("Last item:", fruits[-1])
print("Second from end:", fruits[-2])
print("Third from end:", fruits[-3])


# -----------------------------------------------------------------------------
# 6. Slicing
# -----------------------------------------------------------------------------

print("\n--- 6) Slicing ---")

fruits = ("apple", "banana", "cherry", "orange", "kiwi")

# ساختار عمومی Slicing:
# tuple[start:end]
#
# start شامل می‌شود.
# end شامل نمی‌شود.
#
# پس fruits[1:4] یعنی Indexهای 1 و 2 و 3
print("Slice [1:4]:", fruits[1:4])

# از ابتدا تا قبل از Index 3
print("Slice [:3]:", fruits[:3])

# از Index 2 تا انتها
print("Slice [2:]:", fruits[2:])

# کل Tuple
print("Slice [:]:", fruits[:])


# -----------------------------------------------------------------------------
# 7. Check if Item Exists
# -----------------------------------------------------------------------------

print("\n--- 7) بررسی وجود آیتم ---")

fruits = ("apple", "banana", "cherry")

# عملگر in بررسی می‌کند که آیا مقدار داخل Tuple وجود دارد یا خیر.
print("'banana' in fruits:", "banana" in fruits)

# عملگر not in بررسی می‌کند که مقدار داخل Tuple وجود نداشته باشد.
print("'orange' not in fruits:", "orange" not in fruits)


# -----------------------------------------------------------------------------
# 8. Immutable بودن Tuple
# -----------------------------------------------------------------------------

print("\n--- 8) Immutable بودن Tuple ---")

fruits = ("apple", "banana", "cherry")

# خط زیر عمداً کامنت شده است چون باعث TypeError می‌شود:
#
# fruits[1] = "orange"
#
# دلیل:
# Tuple بعد از ساخته شدن قابل تغییر مستقیم نیست.
# یعنی نمی‌توانیم مقدار یک آیتم را با Index عوض کنیم.


# -----------------------------------------------------------------------------
# 9. Update Tuple با تبدیل به List
# -----------------------------------------------------------------------------

print("\n--- 9) Update Tuple ---")

fruits = ("apple", "banana", "cherry")

# چون Tuple قابل تغییر نیست، برای ایجاد نسخه تغییرکرده:
# 1) آن را به List تبدیل می‌کنیم.
# 2) روی List تغییر را انجام می‌دهیم.
# 3) دوباره List را به Tuple تبدیل می‌کنیم.

temp_list = list(fruits)

# آیتم Index 1 را تغییر می‌دهیم.
temp_list[1] = "orange"

# دوباره Tuple می‌سازیم.
fruits = tuple(temp_list)

print("Updated tuple:", fruits)


# -----------------------------------------------------------------------------
# 10. Add و Remove در Tuple
# -----------------------------------------------------------------------------

print("\n--- 10) Add و Remove در Tuple ---")

fruits = ("apple", "banana", "cherry")

# Tuple متد append() و remove() ندارد.
# بنابراین برای Add/Remove هم می‌توانیم از روش Tuple -> List -> Tuple استفاده کنیم.

temp_list = list(fruits)

# اضافه کردن آیتم
temp_list.append("orange")

# حذف آیتم
temp_list.remove("banana")

fruits = tuple(temp_list)

print("After add/remove:", fruits)


# -----------------------------------------------------------------------------
# 11. Unpacking
# -----------------------------------------------------------------------------

print("\n--- 11) Unpacking ---")

person = ("Ali", 24, "Python")

# در Unpacking، مقادیر Tuple مستقیماً داخل چند متغیر قرار می‌گیرند.
name, age, language = person

print("Name:", name)
print("Age:", age)
print("Language:", language)


# -----------------------------------------------------------------------------
# 12. Extended Unpacking با *
# -----------------------------------------------------------------------------

print("\n--- 12) Extended Unpacking ---")

numbers = (10, 20, 30, 40, 50)

# first اولین مقدار را می‌گیرد.
# last آخرین مقدار را می‌گیرد.
# *middle تمام مقادیر باقی‌مانده را داخل یک List قرار می‌دهد.
first, *middle, last = numbers

print("First:", first)
print("Middle:", middle)
print("Type of middle:", type(middle))
print("Last:", last)


# -----------------------------------------------------------------------------
# 13. Loop روی Tuple
# -----------------------------------------------------------------------------

print("\n--- 13) Loop روی Tuple ---")

fruits = ("apple", "banana", "cherry")

# ساده‌ترین روش پیمایش Tuple:
# هر بار یکی از آیتم‌ها داخل متغیر fruit قرار می‌گیرد.
for fruit in fruits:
    print("Fruit:", fruit)


# -----------------------------------------------------------------------------
# 14. Loop با Index
# -----------------------------------------------------------------------------

print("\n--- 14) Loop با Index ---")

fruits = ("apple", "banana", "cherry")

# len(fruits) تعداد آیتم‌های Tuple را برمی‌گرداند.
# range(...) اعداد 0 تا len-1 را تولید می‌کند.
# سپس با fruits[i] به آیتم مربوط به هر Index دسترسی پیدا می‌کنیم.
for i in range(len(fruits)):
    print("Index:", i, "| Value:", fruits[i])


# -----------------------------------------------------------------------------
# 15. Tuple Method: count()
# -----------------------------------------------------------------------------

print("\n--- 15) Tuple Method: count() ---")

numbers = (10, 20, 10, 30, 10, 40)

# count(value) تعداد دفعات تکرار value را برمی‌گرداند.
print("How many 10s?:", numbers.count(10))

# اگر مقدار وجود نداشته باشد، count() عدد 0 برمی‌گرداند.
print("How many 50s?:", numbers.count(50))


# -----------------------------------------------------------------------------
# 16. Tuple Method: index()
# -----------------------------------------------------------------------------

print("\n--- 16) Tuple Method: index() ---")

numbers = (10, 20, 30, 20, 40)

# index(value) اولین Indexای را که مقدار در آن پیدا می‌شود برمی‌گرداند.
print("First index of 20:", numbers.index(20))

# اگر یک مقدار چند بار تکرار شده باشد، فقط اولین occurrence برگردانده می‌شود.


