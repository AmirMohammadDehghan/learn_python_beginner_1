# -----------------------------------------------------------------------------
# 24. Remove Items با remove()
# -----------------------------------------------------------------------------

print("\n--- 24) remove() ---")

fruits = {"apple", "banana", "cherry"}

# remove(value) مقدار مورد نظر را از Set حذف می‌کند.
