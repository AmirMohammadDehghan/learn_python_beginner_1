# ======================================================
# Type Casting in Python
# تبدیل نوع داده در پایتون
# ======================================================


# ======================================================
# تبدیل به int
# ======================================================

print("=== int() ===")

print(int("25"))
print(int(8.99))
print(int(True))
print(int(False))
print()


# ======================================================
# تبدیل به float
# ======================================================

print("=== float() ===")

print(float(10))
print(float("12.75"))
print(float(True))
print()


# ======================================================
# تبدیل به str
# ======================================================

print("=== str() ===")

print(str(100))
print(str(3.14))
print(str(True))
print()


# ======================================================
# تبدیل به bool
# ======================================================

print("=== bool() ===")

print(bool(0))
print(bool(1))
print(bool(""))
print(bool("Python"))
print(bool([]))
print(bool([1]))
print(bool(None))
print()


# ======================================================
# List Casting
# ======================================================

print("=== list() ===")

print(list((1, 2, 3)))
print(list("Python"))
print()


# ======================================================
# Tuple Casting
# ======================================================

print("=== tuple() ===")

print(tuple([1, 2, 3]))
print(tuple("Python"))
print()


# ======================================================
# Set Casting
# ======================================================

print("=== set() ===")

print(set([1, 2, 2, 3, 3]))
print(set("banana"))
print()


# ======================================================
# Dictionary Casting
# ======================================================

print("=== dict() ===")

print(dict(name="Ali", age=20))
print(dict([("x", 10), ("y", 20)]))
print()


# ======================================================
# Bytes
# ======================================================

print("=== bytes() ===")

print(bytes("Python", "utf-8"))
print(bytes([65, 66, 67]))
print()


# ======================================================
# Bytearray
# ======================================================

print("=== bytearray() ===")

print(bytearray("Python", "utf-8"))
print(bytearray([65, 66, 67]))
print()


# ======================================================
# نمایش نوع داده قبل و بعد از Casting
# ======================================================

print("=== Before & After ===")

value = "150"

print(value, type(value))

value = int(value)

print(value, type(value))
print()


