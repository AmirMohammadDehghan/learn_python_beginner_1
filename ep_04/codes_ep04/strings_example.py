# ======================================================
# 1. ایجاد رشته (Creating Strings)
# ======================================================

text = "Hello Python"
text2 = 'Programming'
text3 = """Multi
Line
String"""

print("=== Creating Strings ===")
print(text)
print(text2)
print(text3)
print()


# ======================================================
# 2. بررسی نوع داده
# ======================================================

print("=== Data Type ===")

print(type(text))     # نمایش نوع داده
print()


# ======================================================
# 3. دسترسی به کاراکترها (Indexing)
# ======================================================

print("=== Indexing ===")

print(text[0])        # اولین کاراکتر
print(text[1])        # دومین کاراکتر
print(text[-1])       # آخرین کاراکتر
print(text[-2])       # یکی مانده به آخر
print()


# ======================================================
# 4. برش رشته (Slicing)
# ======================================================

print("=== Slicing ===")

print(text[:])        # کل رشته
print(text[0:5])      # از اندیس 0 تا قبل از 5
print(text[6:])       # از اندیس 6 تا انتها
print(text[:5])       # از ابتدا تا قبل از 5
print(text[::2])      # هر دو کاراکتر یکی
print(text[::-1])     # معکوس کردن رشته
print()


# ======================================================
# 5. طول رشته
# ======================================================

print("=== Length ===")

print(len(text))      # تعداد کل کاراکترها
print()


# ======================================================
# 6. عملگرهای رشته
# ======================================================

print("=== Operators ===")

print("Hello " + "World")      # اتصال دو رشته
print("Python " * 3)           # تکرار رشته

print("Python" in text)        # بررسی وجود
print("Java" not in text)      # بررسی عدم وجود
print()


# ======================================================
# 7. تغییر حروف
# ======================================================

print("=== Case Methods ===")

print(text.upper())          # تبدیل به حروف بزرگ
print(text.lower())          # تبدیل به حروف کوچک
print(text.title())          # حرف اول هر کلمه بزرگ
print(text.capitalize())     # فقط حرف اول رشته بزرگ
print()


# ======================================================
# 8. حذف فاصله‌های اضافی
# ======================================================

print("=== Strip Methods ===")

sample = "   Hello Python   "

print(sample.strip())        # حذف فاصله ابتدا و انتها
print(sample.lstrip())       # حذف فاصله ابتدا
print(sample.rstrip())       # حذف فاصله انتها
print()


# ======================================================
# 9. جستجو در رشته
# ======================================================

print("=== Search Methods ===")

print(text.find("o"))        # اولین محل قرارگیری
print(text.index("P"))       # اندیس اولین P
print(text.count("o"))       # تعداد تکرار o
print()


# ======================================================
# 10. جایگزینی متن
# ======================================================

print("=== Replace ===")

print(text.replace("Python", "Java"))   # جایگزینی متن
print()


# ======================================================
# 11. تقسیم رشته
# ======================================================

print("=== Split ===")

languages = "Python Java C++ C#"

print(languages.split())        # تقسیم بر اساس فاصله
print(languages.split("a"))     # تقسیم بر اساس حرف a
print()


# ======================================================
# 12. اتصال رشته‌ها
# ======================================================

print("=== Join ===")

items = ["Python", "Java", "C++"]

print(" ".join(items))      # اتصال با فاصله
print("-".join(items))      # اتصال با خط تیره
print(",".join(items))      # اتصال با کاما
print()


# ======================================================
# 13. بررسی ابتدا و انتهای رشته
# ======================================================

print("=== StartsWith / EndsWith ===")

url = "https://python.org"

print(url.startswith("https"))      # آیا با https شروع می‌شود؟
print(url.endswith(".org"))         # آیا با .org پایان می‌یابد؟
print()


# ======================================================
# 14. Escape Characters
# ======================================================

print("=== Escape Characters ===")

print("Hello\nPython")          # رفتن به خط بعد
print("Hello\tPython")          # ایجاد Tab
print("C:\\Users\\Amir")        # نمایش بک‌اسلش
print("She said: \"Hello\"")    # نمایش "
print('It\'s Python')           # نمایش '
print()


# ======================================================
# 15. قالب‌بندی رشته‌ها
# ======================================================

print("=== String Formatting ===")

name = "Ali"
age = 20

print("Name: " + name)                         # اتصال با +
print("Name: {}, Age: {}".format(name, age))   # استفاده از format()
print(f"Name: {name}, Age: {age}")             # استفاده از f-string
print()


# ======================================================
# 16. Immutable بودن رشته
# ======================================================

print("=== Immutable ===")

word = "Python"

print(word)

# word[0] = "J"
# رشته‌ها قابل تغییر نیستند و این خطا ایجاد می‌کند.

new_word = word.replace("P", "J")

print(word)       # مقدار اصلی بدون تغییر
print(new_word)   # رشته جدید
print()


# ======================================================
# 17. مقایسه رشته‌ها
# ======================================================

print("=== Compare Strings ===")

print("Ali" == "Ali")          # مساوی
print("Ali" != "Reza")         # نامساوی
print("Python" > "Java")       # مقایسه بر اساس Unicode
print()


