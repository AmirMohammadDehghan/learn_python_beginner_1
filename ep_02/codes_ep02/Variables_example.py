# ======================================================
# Variables in Python (متغیرها در پایتون)
# دوره مقدماتی پایتون
# ======================================================


# ======================================================
# 1. تعریف متغیر
# ======================================================

name = "Amir"
age = 18
height = 1.82
is_student = True

print(name)
print(age)
print(height)
print(is_student)
print()


# ======================================================
# 2. نمایش مقدار و نوع متغیر
# ======================================================

print(name, type(name))
print(age, type(age))
print(height, type(height))
print(is_student, type(is_student))
print()


# ======================================================
# 3. نام‌گذاری متغیرها
# ======================================================

student_name = "Ali"       # snake_case (استاندارد پایتون)
studentAge = 20            # camelCase
StudentAge = 21            # PascalCase
PI = 3.14159               # ثابت (Convention)

print(student_name)
print(studentAge)
print(StudentAge)
print(PI)
print()


# ======================================================
# 4. قوانین نام متغیر
# ======================================================

user_name = "Sara"     # صحیح
user1 = "Ali"          # صحیح
_user = "Python"       # صحیح

# 1user = "Ali"        # ❌ نباید با عدد شروع شود
# first-name = "Ali"   # ❌ خط تیره مجاز نیست
# class = 10           # ❌ کلمات رزرو شده مجاز نیستند

print(user_name)
print(user1)
print(_user)
print()


# ======================================================
# 5. تغییر مقدار متغیر
# ======================================================

