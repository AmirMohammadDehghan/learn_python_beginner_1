# ======================================================
# print() Function in Python
# آموزش کامل تابع print
# ======================================================


# ======================================================
# 1. چاپ متن
# ======================================================

print("Hello World")
print("Python")
print()


# ======================================================
# 2. چاپ عدد
# ======================================================

print(100)
print(3.14)
print()


# ======================================================
# 3. چاپ چند مقدار
# ======================================================

print("Amir", 18, True, 19.75)
print()


# ======================================================
# 4. چاپ متغیر
# ======================================================

name = "Ali"
age = 20

print(name)
print(age)
print()


# ======================================================
# 5. چاپ متن و متغیر
# ======================================================

print("Name:", name)
print("Age:", age)
print()


# ======================================================
# 6. استفاده از sep
# ======================================================

print("Python", "Java", "C++")
print("Python", "Java", "C++", sep="-")
print("Python", "Java", "C++", sep=" | ")
print("2026", "07", "23", sep="/")
print()


# ======================================================
# 7. استفاده از end
# ======================================================

print("Hello", end=" ")
print("World")

print("Python", end=" ---> ")
print("Programming")
print()


# ======================================================
# 8. استفاده همزمان از sep و end
# ======================================================

print("A", "B", "C", sep="*", end=" END\n")
print()


# ======================================================
# 9. چاپ رشته چند خطی
# ======================================================

print("""
Line 1
Line 2
Line 3
""")
print()


# ======================================================
# 10. کاراکترهای Escape
# ======================================================

print("Hello\nWorld")
print("Python\tProgramming")
print("C:\\Users\\Amir")
print("She said: \"Hello\"")
print("It's Python")
print()


# ======================================================
# 11. چاپ مقادیر محاسباتی
# ======================================================

print(10 + 5)
print(10 * 8)
print(2 ** 5)
print()


# ======================================================
# 12. چاپ نتیجه توابع
# ======================================================

print(len("Python"))
print(type(100))
print(abs(-50))
print(round(3.14159, 2))
print()


# ======================================================
# 13. String Concatenation
# ======================================================

first_name = "Amir"
last_name = "Dehghan"

print(first_name + " " + last_name)
print()


# ======================================================
# 14. String Multiplication
# ======================================================

print("-" * 40)
print("*" * 20)
print()


# ======================================================
# 15. استفاده از f-string (پیشنهادی)
# ======================================================

name = "Sara"
score = 19.75

print(f"Name : {name}")
print(f"Score: {score}")
print(f"{name} scored {score}")
print()


# ======================================================
# 16. استفاده از format()
# ======================================================

print("Name: {} Age: {}".format("Ali", 18))
print("{0} loves {1}".format("Amir", "Python"))
print()


# ======================================================
# 17. چاپ نوع داده
# ======================================================

print(type("Python"))
print(type(100))
print(type(3.14))
print(type(True))
print()


# ======================================================
# 18. چاپ مقادیر بولین
# ======================================================

print(True)
print(False)
print()


# ======================================================
# 19. چاپ لیست، تاپل، دیکشنری و مجموعه
# ======================================================

print([1, 2, 3])
print((1, 2, 3))
print({"name": "Ali", "age": 20})
print({1, 2, 3})
print()


# ======================================================
# 20. چاپ None
# ======================================================

print(None)
print()


# ======================================================
# 21. چاپ جداکننده برای زیبایی خروجی
# ======================================================

print("=" * 50)
print("      Python Print Examples")
print("=" * 50)